'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const window = {};
let resolveSession;
let rejectSession;
let requests = 0;
const context = { window, Headers, AbortController, TypeError, setTimeout, clearTimeout, fetch: () => { requests++; return new Promise((resolve,reject) => { resolveSession = resolve; rejectSession = reject; }); } };
vm.runInNewContext(fs.readFileSync('public/site/js/api.js','utf8'),context);
(async()=>{
  const api = window.AntikApi;
  const stale = api.session({refresh:true});
  const authenticated = {authenticated:true,user:{id:'new-user'},csrfToken:'new-csrf'};
  api.setSession(authenticated);
  resolveSession({ok:true,headers:new Headers({'Content-Type':'application/json'}),json:async()=>({authenticated:false})});
  assert.equal(await stale,authenticated);
  assert.equal(await api.session(),authenticated);
  const staleLogout = api.session({refresh:true});
  const loggedOut={authenticated:false};
  api.setSession(loggedOut);
  resolveSession({ok:true,headers:new Headers({'Content-Type':'application/json'}),json:async()=>authenticated});
  assert.equal(await staleLogout,loggedOut);
  console.log('PASS  stale session fetch cannot overwrite automatic login or restore a logged-out UI session');
  const first=api.session({refresh:true}), second=api.session({refresh:true});
  assert.equal(requests,3);
  resolveSession({ok:true,headers:new Headers({'Content-Type':'application/json'}),json:async()=>authenticated});
  assert.equal(await first,authenticated); assert.equal(await second,authenticated);
  const failed=api.session({refresh:true});
  rejectSession(new TypeError('offline'));
  await assert.rejects(failed,/связи/);
  assert.equal(await api.session(),authenticated);
  const obsoleteFailure=api.session({refresh:true});
  api.setSession(loggedOut); rejectSession(new TypeError('offline'));
  assert.equal(await obsoleteFailure,loggedOut);
  console.log('PASS  session requests coalesce, network failures preserve confirmed state, stale failures cannot undo logout');
})().catch(error=>{console.error(error);process.exitCode=1;});
